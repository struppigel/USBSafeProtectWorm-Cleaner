        void DoScan()
        {
            Busy(true, "Scanning...");
            new Thread(() =>
            {
                var res = engine.Scan();
                BeginInvoke(new Action(() =>
                {
                    findings = res;
                    lv.BeginUpdate(); lv.Items.Clear();
                    foreach (var f in res)
                    {
                        var it = new ListViewItem(new[] { f.KindText, Ioc.Show(f.Title), Ioc.Show(f.Detail) }) { Tag = f, Checked = f.Selected };
                        lv.Items.Add(it);
                    }
                    lv.EndUpdate();
                    Busy(false, res.Count == 0 ? "No traces of the worm found." : res.Count + " finding(s). Review and click \"Clean selected\".");
                    status.ForeColor = res.Count == 0 ? Color.DarkGreen : Color.DarkRed;
                }));
            }) { IsBackground = true }.Start();
        }

        void DoClean()
        {
            var sel = findings.Where(f => f.Selected).ToList();
            if (sel.Count == 0) return;
            if (MessageBox.Show(this, "Clean " + sel.Count + " selected item(s)?\n\nWorm processes will be terminated, persistence and worm files removed, " +
                "and hidden files moved back to the drive root.", Text, MessageBoxButtons.OKCancel, MessageBoxIcon.Question) != DialogResult.OK) return;
            engine.Quarantine = chkQ.Checked;
            Busy(true, "Cleaning...");
            new Thread(() =>
            {
                engine.Clean(sel);
                BeginInvoke(new Action(() => { engine.Log(""); engine.Log(Engine.Fmt("INFO", "Scanning again to verify the result")); DoScan(); }));
            }) { IsBackground = true }.Start();
        }

