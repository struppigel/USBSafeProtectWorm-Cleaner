        void DeleteQuarantine()
        {
            int files; long bytes;
            Engine.QuarantineInfo(out files, out bytes);
            if (files == 0)
            {
                MessageBox.Show(this, "The quarantine is empty.", Text, MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
