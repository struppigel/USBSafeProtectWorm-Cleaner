        void Busy(bool busy, string text)
        {
            btnScan.Enabled = btnAdd.Enabled = btnDelQ.Enabled = !busy;
            btnClean.Enabled = !busy && findings.Any();
            status.Text = text;
            Cursor = busy ? Cursors.WaitCursor : Cursors.Default;
