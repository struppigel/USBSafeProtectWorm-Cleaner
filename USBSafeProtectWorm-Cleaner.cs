// USBSafeProtectWorm-Cleaner - removal & file-recovery tool for the "Usb Safe Protect" USB worm
// (AmindPDFCore.dll side-loading via C:\ProgramData\Nahimic, HKCU Run "Nahimics").
//
// What it does:
//   1. Terminates worm processes (AmindPDFCore.exe "trial" from ProgramData\Nahimic, the
//      "Usb Safe Protect.exe" launcher, any process owning the hidden "UsbSafeProtect" window).
//   2. Removes Run/RunOnce persistence for every user (loaded hives, and offline NTUSER.DAT
//      hives when run as administrator) plus HKLM.
//   3. Removes the worm files from %ProgramData%\Nahimic (only the worm's own files; the folder is
//      removed only if it is empty afterwards).
//   4. On every drive / share: deletes the launcher and the payload folder and moves the victim's
//      files out of the invisible folder X:\U+206C U+206C\U+206C U+206D back to the root. Nothing
//      is ever overwritten: name clashes are restored as "name (restored).ext".
//   Removed malware is optionally quarantined as XOR-0xFF encoded copies.
//
// Build (any Windows with .NET Framework 4.x, no SDK required):
//   %WINDIR%\Microsoft.NET\Framework64\v4.0.30319\csc.exe /nologo /target:winexe /optimize+
//     /r:System.Management.dll /r:System.Windows.Forms.dll /r:System.Drawing.dll
//     /win32manifest:app.manifest /win32icon:app.ico /out:USBSafeProtectWorm-Cleaner.exe USBSafeProtectWorm-Cleaner.cs
//   (app.ico is generated by make_icon.py)
//
// Command line (same engine, no GUI):  USBSafeProtectWorm-Cleaner.exe /scan | /clean [/path \\nas\share ...] [/noquarantine] [/deletequarantine] [/log file]
//   /deletequarantine alone only empties %ProgramData%\USBSafeProtectWorm-Cleaner\Quarantine; combined with /clean it runs after cleaning.
// Every run (GUI or CLI) also writes USBSafeProtectWorm-Cleaner_<yyyyMMdd_HHmmss>.txt next to the executable
// (fallback: %ProgramData%\USBSafeProtectWorm-Cleaner\Logs when the exe folder is read-only).
// C# 5 on purpose: compiles with the csc.exe that ships with every Windows 10.

