        // Makes invisible names readable in the UI/log.
        public static string Show(string s)
        {
            if (s == null) return "";
            var sb = new StringBuilder();
            foreach (char c in s)
            {
                if (c >= '\u2060' && c <= '\u206F') sb.AppendFormat("<U+{0:X4}>", (int)c);
                else sb.Append(c);
            }
            return sb.ToString();
        }

        public static string Sha256(string path)
        {
            try
            {
                using (var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete))
                using (var sha = SHA256.Create())
                    return BitConverter.ToString(sha.ComputeHash(fs)).Replace("-", "").ToLowerInvariant();
            }
            catch { return null; }
        }

        public static bool IsKnown(string path)
        {
            string h = Sha256(path);
            return h != null && KnownHashes.ContainsKey(h);
        }

        public static bool IsWormRunCommand(string data)
        {
            if (string.IsNullOrEmpty(data)) return false;
            string d = data.ToLowerInvariant();
            if (!d.Contains("amindpdfcore")) return false;
            return d.Contains("\\programdata\\nahimic\\") || d.Contains(" trial") || d.Contains("usb safe protect");
        }
