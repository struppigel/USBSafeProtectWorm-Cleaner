    static class Program
    {
        [STAThread]
        static int Main(string[] args)
        {
            SessionLog.Init();
            bool delQ = args.Any(a => a.Equals("/deletequarantine", StringComparison.OrdinalIgnoreCase));
            bool doScan = args.Any(a => a.Equals("/scan", StringComparison.OrdinalIgnoreCase) || a.Equals("/clean", StringComparison.OrdinalIgnoreCase));
            bool cli = doScan || delQ;
            if (!cli)
            {
                Application.EnableVisualStyles();
                Application.SetCompatibleTextRenderingDefault(false);
                Application.Run(new MainForm());
                return 0;
            }

            var engine = new Engine();
            string logFile = null;
            for (int i = 0; i < args.Length; i++)
            {
                if (args[i].Equals("/path", StringComparison.OrdinalIgnoreCase) && i + 1 < args.Length) engine.ExtraPaths.Add(args[++i]);
                else if (args[i].Equals("/log", StringComparison.OrdinalIgnoreCase) && i + 1 < args.Length) logFile = args[++i];
                else if (args[i].Equals("/noquarantine", StringComparison.OrdinalIgnoreCase)) engine.Quarantine = false;
            }
            var sb = new StringBuilder();
            engine.Log = m => { sb.AppendLine(m); SessionLog.Write(m); try { Console.WriteLine(m); } catch { } };
            engine.Log(SessionLog.Describe());
            if (!doScan)
            {
                bool ok = engine.DeleteQuarantine();
                if (logFile != null) File.WriteAllText(logFile, sb.ToString(), Encoding.UTF8);
                return ok ? 0 : 2;
            }
            var found = engine.Scan();
            if (args.Any(a => a.Equals("/clean", StringComparison.OrdinalIgnoreCase)) && found.Count > 0)
            {
                engine.Clean(found);
                found = engine.Scan();
            }
            if (delQ) engine.DeleteQuarantine();
            if (logFile != null) File.WriteAllText(logFile, sb.ToString(), Encoding.UTF8);
            return found.Count == 0 ? 0 : 1;
        }
    }
