    // ------------------------------------------------------------------ findings
    enum Kind { Process, Registry, InstallFolder, Volume }

    class Finding
    {
        public Kind Kind;
        public string Title;
        public string Detail;
        public bool Selected = true;
        // payload
        public int Pid;
        public string Path;
        public RegistryHive Hive;
        public RegistryView View;
        public string SubKey;
        public string ValueName;
        public string OfflineSid;      // non-null => hive is loaded from NTUSER.DAT on demand
        public string OfflineHivePath;

        public string KindText
        {
            get
            {
                switch (Kind)
                {
                    case Kind.Process: return "Running process";
                    case Kind.Registry: return "Persistence";
                    case Kind.InstallFolder: return "Worm files";
                    default: return "Infected drive";
                }
            }
        }
    }

    // ------------------------------------------------------------------ engine
    class Engine
    {
        public Action<string> Log = delegate { };

        // One log line: a fixed-width level word, then a plain sentence.
        public static string Fmt(string level, string msg) { return level.PadRight(10) + msg; }
        void L(string level, string msg) { Log(Fmt(level, msg)); }
        public bool Quarantine = true;
        public readonly List<string> ExtraPaths = new List<string>();
        string quarantineDir;

        public static bool IsAdmin
        {
            get { return new WindowsPrincipal(WindowsIdentity.GetCurrent()).IsInRole(WindowsBuiltInRole.Administrator); }
        }

        static readonly string[] RunKeys =
        {
            @"Software\Microsoft\Windows\CurrentVersion\Run",
            @"Software\Microsoft\Windows\CurrentVersion\RunOnce",
            @"Software\WOW6432Node\Microsoft\Windows\CurrentVersion\Run",
            @"Software\WOW6432Node\Microsoft\Windows\CurrentVersion\RunOnce",
        };

        // ============================ SCAN ============================
        public List<Finding> Scan()
        {
            var list = new List<Finding>();
            Log(""); L("INFO", "Scan started" + (IsAdmin ? " (administrator)" : " (standard user: other users' offline registry hives are skipped)"));
            try { ScanProcesses(list); } catch (Exception ex) { L("ERROR", "Process scan failed: " + ex.Message); }
            try { ScanRegistry(list); } catch (Exception ex) { L("ERROR", "Registry scan failed: " + ex.Message); }
            try { ScanInstallFolder(list); } catch (Exception ex) { L("ERROR", "Install folder scan failed: " + ex.Message); }
            try { ScanVolumes(list); } catch (Exception ex) { L("ERROR", "Drive scan failed: " + ex.Message); }
            L("INFO", list.Count == 0 ? "Scan finished: no traces of the worm found" : string.Format("Scan finished: {0} finding(s)", list.Count));
            return list;
        }

        void ScanProcesses(List<Finding> list)
        {
            var windowPids = WindowPids(Ioc.WindowClass);
            string inst = Ioc.InstallDir.TrimEnd('\\') + "\\";
            using (var s = new ManagementObjectSearcher("SELECT ProcessId, Name, ExecutablePath, CommandLine FROM Win32_Process"))
            {
                foreach (ManagementObject mo in s.Get())
                {
                    int pid = Convert.ToInt32(mo["ProcessId"]);
                    string name = (mo["Name"] as string) ?? "";
                    string exe = (mo["ExecutablePath"] as string) ?? "";
                    string cmd = (mo["CommandLine"] as string) ?? "";
                    string why = null;
                    if (exe.StartsWith(inst, StringComparison.OrdinalIgnoreCase)) why = "runs from " + Ioc.InstallDir;
                    else if (name.Equals(Ioc.Launcher, StringComparison.OrdinalIgnoreCase)) why = "worm launcher";
                    else if (name.Equals("AmindPDFCore.exe", StringComparison.OrdinalIgnoreCase) &&
                             cmd.TrimEnd().EndsWith(" trial", StringComparison.OrdinalIgnoreCase)) why = "side-loading host started with 'trial'";
                    else if (windowPids.Contains(pid)) why = "owns hidden '" + Ioc.WindowClass + "' window";
                    else if (name.Equals("AmindPDFCore.exe", StringComparison.OrdinalIgnoreCase) && exe.Length > 0)
                    {
                        string dll = Path.Combine(Path.GetDirectoryName(exe), "AmindPDFCore.dll");
                        if (File.Exists(dll) && Ioc.IsKnown(dll)) why = "loads known malicious AmindPDFCore.dll";
                    }
                    if (why == null) continue;
                    var f = new Finding { Kind = Kind.Process, Pid = pid, Path = exe,
                        Title = string.Format("{0} (PID {1})", name, pid), Detail = why + " | " + cmd };
                    list.Add(f);
                    L("FOUND", f.KindText + ": " + f.Title + " - " + f.Detail);
                }
            }
        }

        void ScanRegistry(List<Finding> list)
        {
            // HKLM, both views
            foreach (var view in new[] { RegistryView.Registry64, RegistryView.Registry32 })
                using (var b = RegistryKey.OpenBaseKey(RegistryHive.LocalMachine, view))
                    foreach (var rk in new[] { RunKeys[0], RunKeys[1] })
                        ScanRunKey(list, b, RegistryHive.LocalMachine, view, rk, "HKLM" + (view == RegistryView.Registry32 ? " (32-bit)" : ""), null, null);

            // Every hive loaded under HKU (all logged-on users; access to others needs admin)
            var loaded = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            using (var hku = RegistryKey.OpenBaseKey(RegistryHive.Users, RegistryView.Registry64))
            {
                foreach (var sid in hku.GetSubKeyNames())
                {
                    if (sid.EndsWith("_Classes", StringComparison.OrdinalIgnoreCase)) continue;
                    loaded.Add(sid);
                    foreach (var rk in RunKeys)
                        ScanRunKey(list, hku, RegistryHive.Users, RegistryView.Registry64, sid + "\\" + rk, "HKU", null, null);
                }
            }

            // Users that are not logged on: load their NTUSER.DAT (admin only)
            if (!IsAdmin) return;
            foreach (var prof in OfflineProfiles(loaded))
            {
                string mount = MountName(prof.Key);
                if (!RegLoad(mount, prof.Value)) continue;
                try
                {
                    using (var hku = RegistryKey.OpenBaseKey(RegistryHive.Users, RegistryView.Registry64))
                        foreach (var rk in RunKeys)
                            ScanRunKey(list, hku, RegistryHive.Users, RegistryView.Registry64, mount + "\\" + rk,
                                "offline " + prof.Key, prof.Key, prof.Value);
                }
                finally { RegUnload(mount); }
            }
        }

        void ScanRunKey(List<Finding> list, RegistryKey baseKey, RegistryHive hive, RegistryView view, string sub, string label, string offSid, string offPath)
        {
            RegistryKey k = null;
            try { k = baseKey.OpenSubKey(sub, false); } catch { return; }
            if (k == null) return;
            using (k)
            {
                foreach (var vn in k.GetValueNames())
                {
                    string data = Convert.ToString(k.GetValue(vn, "", RegistryValueOptions.DoNotExpandEnvironmentNames));
                    bool hit = Ioc.IsWormRunCommand(data) ||
                               (vn.Equals(Ioc.RunValueName, StringComparison.OrdinalIgnoreCase) && data.ToLowerInvariant().Contains("amindpdfcore"));
                    if (!hit) continue;
                    string shownKey = offSid != null ? sub.Substring(sub.IndexOf('\\') + 1) : sub;
                    var f = new Finding
                    {
                        Kind = Kind.Registry, Hive = hive, View = view, SubKey = sub, ValueName = vn,
                        OfflineSid = offSid, OfflineHivePath = offPath,
                        Title = label + "\\" + shownKey + " : " + vn,
                        Detail = data
                    };
                    list.Add(f);
                    L("FOUND", f.KindText + ": " + f.Title + " = " + data);
                }
            }
        }

        void ScanInstallFolder(List<Finding> list)
        {
            string dir = Ioc.InstallDir;
            if (!Directory.Exists(dir)) return;
            var present = Ioc.InstallFiles.Where(n => File.Exists(Path.Combine(dir, n))).ToList();
            if (present.Count == 0) return;
            var known = present.Where(n => Ioc.IsKnown(Path.Combine(dir, n))).ToList();
            var f = new Finding
            {
                Kind = Kind.InstallFolder, Path = dir, Title = dir,
                Detail = "contains " + string.Join(", ", present) + (known.Count > 0 ? " | known malicious hash: " + string.Join(", ", known) : "")
            };
            list.Add(f);
            L("FOUND", f.KindText + ": " + f.Title + " - " + f.Detail);
        }

        [DllImport("mpr.dll", CharSet = CharSet.Unicode)]
        static extern int WNetGetConnection(string local, StringBuilder remote, ref int len);

        static string UncOf(string driveRoot)
        {
            var sb = new StringBuilder(1024); int len = sb.Capacity;
            return WNetGetConnection(driveRoot.Substring(0, 2), sb, ref len) == 0 ? sb.ToString().TrimEnd('\\') : null;
        }

        public List<string> ScanRoots()
        {
            var roots = new List<string>();
            var mappedUnc = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var d in DriveInfo.GetDrives())
            {
                try
                {
                    if (d.DriveType == DriveType.CDRom || d.DriveType == DriveType.NoRootDirectory) continue;
                    roots.Add(d.RootDirectory.FullName);
                    if (d.DriveType == DriveType.Network) { var u = UncOf(d.Name); if (u != null) mappedUnc.Add(u); }
                }
                catch { }
            }
            // Mapped network drives of the user are invisible to an elevated process; scan the UNC paths too.
            try
            {
                using (var net = Registry.CurrentUser.OpenSubKey("Network"))
                    if (net != null)
                        foreach (var letter in net.GetSubKeyNames())
                            using (var k = net.OpenSubKey(letter))
                            {
                                var rp = k == null ? null : k.GetValue("RemotePath") as string;
                                if (!string.IsNullOrEmpty(rp)) roots.Add(rp);
                            }
            }
            catch { }
            roots.AddRange(ExtraPaths);
            // dedupe (case-insensitive, ignore trailing slash); a UNC path already reachable via a mapped letter is skipped
            var seen = new HashSet<string>(mappedUnc, StringComparer.OrdinalIgnoreCase);
            return roots.Where(r => seen.Add(r.TrimEnd('\\'))).ToList();
        }

        void ScanVolumes(List<Finding> list)
        {
            foreach (var root in ScanRoots())
            {
                string r = root.TrimEnd('\\') + "\\";
                L("INFO", "Checking " + r);
                bool ready;
                try { ready = Directory.Exists(r); } catch { ready = false; }
                if (!ready) continue;
                string top = r + Ioc.TopDir;
                string launcher = r + Ioc.Launcher;
                bool hasTop = Directory.Exists(top);
                bool hasLauncher = File.Exists(launcher);
                if (!hasTop && !hasLauncher) continue;

                var det = new List<string>();
                if (hasLauncher) det.Add(Ioc.Launcher + (Ioc.IsKnown(launcher) ? " (known hash)" : " (unknown hash)"));
                if (hasTop)
                {
                    string files = Path.Combine(top, Ioc.FilesDir);
                    int n = 0;
                    try { if (Directory.Exists(files)) n = Directory.EnumerateFileSystemEntries(files).Count(); } catch { }
                    det.Add(n + " hidden item(s) to restore");
                    if (Directory.Exists(Path.Combine(top, Ioc.PayloadDir))) det.Add("payload folder present");
                }
                var f = new Finding { Kind = Kind.Volume, Path = r, Title = r, Detail = string.Join(", ", det) };
                // A lone launcher with an unrecognised hash is not removed unless the user ticks it.
                if (!hasTop && !Ioc.IsKnown(launcher)) f.Selected = false;
                list.Add(f);
                L("FOUND", f.KindText + ": " + f.Title + " - " + f.Detail);
            }
        }

        // ============================ CLEAN ============================
        public void Clean(List<Finding> findings)
        {
            Log(""); L("INFO", "Cleaning started");
            quarantineDir = null;
            // Order matters: stop the worm first so it cannot re-hide files while we restore them.
            foreach (var f in findings.Where(x => x.Selected && x.Kind == Kind.Process)) Safe(f, KillProcess);
            foreach (var f in findings.Where(x => x.Selected && x.Kind == Kind.Registry)) Safe(f, DeleteRunValue);
            foreach (var f in findings.Where(x => x.Selected && x.Kind == Kind.InstallFolder)) Safe(f, CleanInstallFolder);
            foreach (var f in findings.Where(x => x.Selected && x.Kind == Kind.Volume)) Safe(f, RestoreVolume);
            if (quarantineDir != null) L("INFO", "Quarantined copies are in " + quarantineDir);
            L("INFO", "Cleaning finished");
        }

        void Safe(Finding f, Action<Finding> a)
        {
            try { a(f); }
            catch (Exception ex) { L("ERROR", f.Title + ": " + ex.Message); }
        }

        void KillProcess(Finding f)
        {
            Process p;
            try { p = Process.GetProcessById(f.Pid); }
            catch (ArgumentException) { L("SKIPPED", "Process " + f.Pid + " is no longer running"); return; }
            p.Kill();
            p.WaitForExit(5000);
            L("REMOVED", "Terminated process " + f.Title);
        }

        void DeleteRunValue(Finding f)
        {
            string mount = null;
            if (f.OfflineSid != null)
            {
                mount = MountName(f.OfflineSid);
                if (!RegLoad(mount, f.OfflineHivePath)) throw new Exception("cannot load hive " + f.OfflineHivePath);
            }
            try
            {
                using (var b = RegistryKey.OpenBaseKey(f.Hive, f.View))
                using (var k = b.OpenSubKey(f.SubKey, true))
                {
                    if (k == null || k.GetValue(f.ValueName) == null) { L("SKIPPED", "Run value no longer exists: " + f.Title); return; }
                    k.DeleteValue(f.ValueName);
                }
                L("REMOVED", "Run value " + f.Title);
            }
            finally { if (mount != null) RegUnload(mount); }
        }

        void CleanInstallFolder(Finding f)
        {
            foreach (var n in Ioc.InstallFiles)
            {
                string p = Path.Combine(f.Path, n);
                if (File.Exists(p)) RemoveMalware(p);
            }
            if (Directory.Exists(f.Path) && !Directory.EnumerateFileSystemEntries(f.Path).Any())
            {
                Directory.Delete(f.Path);
                L("REMOVED", "Folder " + f.Path);
            }
            else if (Directory.Exists(f.Path))
                L("SKIPPED", f.Path + " still contains other files, so it was left in place");
        }

        void RestoreVolume(Finding f)
        {
            string r = f.Path;
            string top = r + Ioc.TopDir;
            string files = Path.Combine(top, Ioc.FilesDir);
            string payload = Path.Combine(top, Ioc.PayloadDir);
            L("INFO", "Restoring drive " + r);

            string launcher = r + Ioc.Launcher;
            if (File.Exists(launcher)) RemoveMalware(launcher);

            if (Directory.Exists(payload))
            {
                foreach (var p in Directory.GetFiles(payload, "*", SearchOption.AllDirectories)) RemoveMalware(p);
                ForceDeleteDir(payload);
                L("REMOVED", "Payload folder " + Ioc.Show(payload));
            }

            int moved = 0, renamed = 0, failed = 0;
            if (Directory.Exists(files))
            {
                foreach (var src in Directory.GetFileSystemEntries(files))
                {
                    string name = Path.GetFileName(src);
                    bool isDir = Directory.Exists(src);
                    // A second infection moves the previous launcher in here as well.
                    if (!isDir && name.Equals(Ioc.Launcher, StringComparison.OrdinalIgnoreCase) && Ioc.IsKnown(src))
                    {
                        RemoveMalware(src);
                        continue;
                    }
                    string dst = r + name;
                    bool clash = File.Exists(dst) || Directory.Exists(dst);
                    if (clash) dst = FreeName(r, name, isDir);
                    try
                    {
                        if (isDir) Directory.Move(src, dst); else File.Move(src, dst);
                        moved++;
                        if (clash) { renamed++; L("RENAMED", "Name already in use, restored as " + Ioc.Show(dst)); }
                    }
                    catch (Exception ex)
                    {
                        failed++;
                        L("ERROR", "Could not restore " + Ioc.Show(src) + ": " + ex.Message);
                    }
                }
                if (!Directory.EnumerateFileSystemEntries(files).Any()) ForceDeleteDir(files);
            }
            L(failed > 0 ? "ERROR" : "RESTORED", string.Format("{0} item(s) moved back to {1}{2}{3}", moved, r,
                renamed > 0 ? ", " + renamed + " under a new name" : "", failed > 0 ? ", " + failed + " FAILED" : ""));

            if (Directory.Exists(top))
            {
                if (!Directory.EnumerateFileSystemEntries(top).Any())
                {
                    ForceDeleteDir(top);
                    L("REMOVED", "Hidden folder " + Ioc.Show(top));
                }
                else
                    L("ERROR", Ioc.Show(top) + " still contains items and was left in place; check it manually");
            }
        }

        static string FreeName(string dir, string name, bool isDir)
        {
            string stem = isDir ? name : Path.GetFileNameWithoutExtension(name);
            string ext = isDir ? "" : Path.GetExtension(name);
            for (int i = 1; ; i++)
            {
                string cand = dir + stem + (i == 1 ? " (restored)" : " (restored " + i + ")") + ext;
                if (!File.Exists(cand) && !Directory.Exists(cand)) return cand;
            }
        }

        public static string QuarantineRoot
        {
            get { return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData), "USBSafeProtectWorm-Cleaner", "Quarantine"); }
        }

        // Number of files and total bytes currently in quarantine (all runs).
        public static void QuarantineInfo(out int files, out long bytes)
        {
            files = 0; bytes = 0;
            if (!Directory.Exists(QuarantineRoot)) return;
            foreach (var f in Directory.GetFiles(QuarantineRoot, "*", SearchOption.AllDirectories))
            {
                files++;
                try { bytes += new FileInfo(f).Length; } catch { }
            }
        }

        // Permanently deletes every quarantined sample and manifest.
        public bool DeleteQuarantine()
        {
            int files; long bytes;
            QuarantineInfo(out files, out bytes);
            if (!Directory.Exists(QuarantineRoot)) { L("SKIPPED", "The quarantine is empty (" + QuarantineRoot + " does not exist)"); return true; }
            Log(""); L("INFO", string.Format("Deleting the quarantine: {0} file(s), {1:N0} bytes in {2}", files, bytes, QuarantineRoot));
            try
            {
                ForceDeleteDir(QuarantineRoot);
                L("REMOVED", "Quarantine deleted");
                return true;
            }
            catch (Exception ex)
            {
                int left; long leftBytes;
                QuarantineInfo(out left, out leftBytes);
                L("ERROR", "Could not delete all of the quarantine: " + ex.Message + " (" + left + " file(s) left; another user's quarantine may need \"Restart as admin\")");
                return false;
            }
        }

        static void ForceDeleteDir(string d)
        {
            foreach (var p in Directory.GetFileSystemEntries(d, "*", SearchOption.AllDirectories))
                try { File.SetAttributes(p, FileAttributes.Normal); } catch { }
            try { File.SetAttributes(d, FileAttributes.Directory); } catch { }
            Directory.Delete(d, true);
        }

        void RemoveMalware(string path)
        {
            string hash = Ioc.Sha256(path);
            string what;
            string label = hash != null && Ioc.KnownHashes.TryGetValue(hash, out what) ? what : "unrecognised hash";
            if (Quarantine && hash != null)
            {
                try
                {
                    if (quarantineDir == null)
                    {
                        quarantineDir = Path.Combine(QuarantineRoot, DateTime.Now.ToString("yyyyMMdd_HHmmss"));
                        Directory.CreateDirectory(quarantineDir);
                    }
                    byte[] b = File.ReadAllBytes(path);
                    for (int i = 0; i < b.Length; i++) b[i] ^= 0xFF;
                    string q = Path.Combine(quarantineDir, hash + "_" + Path.GetFileName(path) + ".xff");
                    if (!File.Exists(q)) File.WriteAllBytes(q, b);
                    File.AppendAllText(Path.Combine(quarantineDir, "manifest.txt"),
                        string.Format("{0}\t{1}\t{2}\t{3}\r\n", DateTime.Now.ToString("s"), hash, Ioc.Show(path), label), Encoding.UTF8);
                }
                catch (Exception ex) { L("ERROR", "Could not quarantine " + Ioc.Show(path) + ": " + ex.Message); }
            }
            File.SetAttributes(path, FileAttributes.Normal);
            File.Delete(path);
            L("REMOVED", "File " + Ioc.Show(path) + " - " + label + ", SHA-256 " + (hash ?? "unknown"));
        }

        // ============================ helpers ============================
        static IEnumerable<KeyValuePair<string, string>> OfflineProfiles(HashSet<string> loaded)
        {
            using (var pl = Registry.LocalMachine.OpenSubKey(@"SOFTWARE\Microsoft\Windows NT\CurrentVersion\ProfileList"))
            {
                if (pl == null) yield break;
                foreach (var sid in pl.GetSubKeyNames())
                {
                    if (!sid.StartsWith("S-1-5-21-") || loaded.Contains(sid)) continue;
                    string img;
                    using (var k = pl.OpenSubKey(sid)) img = k == null ? null : Environment.ExpandEnvironmentVariables(Convert.ToString(k.GetValue("ProfileImagePath", "")));
                    if (string.IsNullOrEmpty(img)) continue;
                    string nt = Path.Combine(img, "NTUSER.DAT");
                    if (File.Exists(nt)) yield return new KeyValuePair<string, string>(sid, nt);
                }
            }
        }

        static string MountName(string sid) { return "USPC_" + sid; }

        bool RegLoad(string mount, string file)
        {
            int rc = RunReg("load \"HKU\\" + mount + "\" \"" + file + "\"");
            if (rc != 0) L("ERROR", "Could not load registry hive " + file + " (in use or no permission)");
            return rc == 0;
        }

        void RegUnload(string mount)
        {
            GC.Collect(); GC.WaitForPendingFinalizers();
            for (int i = 0; i < 5; i++)
            {
                if (RunReg("unload \"HKU\\" + mount + "\"") == 0) return;
                Thread.Sleep(300);
            }
            L("ERROR", "Could not unload registry hive HKU\\" + mount);
        }

        static int RunReg(string args)
        {
            var psi = new ProcessStartInfo(Path.Combine(Environment.SystemDirectory, "reg.exe"), args)
            { CreateNoWindow = true, UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true };
            using (var p = Process.Start(psi))
            {
                p.StandardOutput.ReadToEnd(); p.StandardError.ReadToEnd();
                p.WaitForExit();
                return p.ExitCode;
            }
        }

        delegate bool EnumWindowsProc(IntPtr hWnd, IntPtr lParam);
        [DllImport("user32.dll")] static extern bool EnumWindows(EnumWindowsProc cb, IntPtr lParam);
        [DllImport("user32.dll", CharSet = CharSet.Unicode)] static extern int GetClassName(IntPtr hWnd, StringBuilder sb, int max);
        [DllImport("user32.dll")] static extern uint GetWindowThreadProcessId(IntPtr hWnd, out uint pid);

        static HashSet<int> WindowPids(string cls)
        {
            var pids = new HashSet<int>();
            EnumWindows((h, l) =>
            {
                var sb = new StringBuilder(256);
                GetClassName(h, sb, sb.Capacity);
                if (sb.ToString() == cls) { uint pid; GetWindowThreadProcessId(h, out pid); pids.Add((int)pid); }
                return true;
            }, IntPtr.Zero);
            return pids;
        }
    }

    // ------------------------------------------------------------------ session log file
    // Every run writes USBSafeProtectWorm-Cleaner_<timestamp>.txt next to the executable (each line is appended
    // immediately, so the file survives a crash). Falls back to %ProgramData% if that folder is read-only.
    static class SessionLog
    {
        static readonly object sync = new object();
        public static string FilePath { get; private set; }
        public static string FallbackReason { get; private set; }

        public static void Init()
        {
            string name = "USBSafeProtectWorm-Cleaner_" + DateTime.Now.ToString("yyyyMMdd_HHmmss") + ".txt";
            string exeDir = Path.GetDirectoryName(Application.ExecutablePath);
            string header = string.Format("USBSafeProtectWorm-Cleaner - log started {0} on {1} as {2}\\{3}{4}{5}",
                DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss"), Environment.MachineName, Environment.UserDomainName, Environment.UserName,
                Engine.IsAdmin ? " (administrator)" : "", Environment.NewLine);
            try
            {
                FilePath = Path.Combine(exeDir, name);
                File.AppendAllText(FilePath, header, Encoding.UTF8);
                return;
            }
            catch (Exception ex) { FallbackReason = exeDir + " is not writable (" + ex.Message + ")"; }
            try
            {
                string dir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData), "USBSafeProtectWorm-Cleaner", "Logs");
                Directory.CreateDirectory(dir);
                FilePath = Path.Combine(dir, name);
                File.AppendAllText(FilePath, header, Encoding.UTF8);
            }
            catch { FilePath = null; }
        }

        public static void Write(string line)
        {
            if (FilePath == null) return;
            lock (sync)
            {
                string text = string.IsNullOrEmpty(line) ? "" : DateTime.Now.ToString("HH:mm:ss") + "  " + line;
                try { File.AppendAllText(FilePath, text + Environment.NewLine, Encoding.UTF8); }
                catch { }
            }
        }

        public static string Describe()
        {
            if (FilePath == null) return Engine.Fmt("ERROR", "Could not create a log file");
            return FallbackReason != null ? Engine.Fmt("WARNING", FallbackReason + "; writing the log to " + FilePath) : Engine.Fmt("INFO", "Log file: " + FilePath);
        }
    }

